export type TranslationKey = keyof typeof translations.ru;

type Replacements = Record<string, string | number>;

export const getTranslator = (language: AppLanguage = "ru") => {
    const dictionary = translations[language] || translations.ru;

    return (key: TranslationKey, replacements: Replacements = {}) => {
        const template: string = dictionary[key] || translations.ru[key] || key;

        return Object.entries(replacements).reduce<string>(
            (result, [name, value]) => result.split(`{${name}}`).join(String(value)),
            template
        );
    };
};
